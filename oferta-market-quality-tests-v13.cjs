const s=api.statusFor(0,0);
assert.equal(s.key,'unverified');
assert.match(s.detail,/Verificação individual não comprovada/);
assert.ok(!/mercado sem ofertas|verificada, sem ofertas/i.test(s.heading));
const branch=fs.readFileSync('oferta-branch-offers-v11.js','utf8');
assert.ok(branch.includes('summary.dataset.obBranchText!==signature'),'prevents redundant updates');
